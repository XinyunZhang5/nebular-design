# Glazing.
#
# A window at this scale is not a window part. The catalogue's window frames are
# two courses tall and a fixed four studs wide, so placing one means finding an
# opening of exactly that size and hoping the building agrees; and the moment one
# lands half a course out, the whole wall around it has to shift. What LEGO's own
# Architecture sets do instead is simpler and looks better: ordinary brick shapes
# in a transparent colour. The geometry is unchanged, every size in the brick
# table is available, and the result reads as glass because it *is* glass.
#
# Trans-Brown is the default because it is smoked glass, which is what a window
# in a photograph almost always is — a dark opening, not a clear one. Trans-Clear
# reads as a hole in the wall from most angles.


# The one used unless a caller says otherwise.
DEFAULT_GLAZING_ID = 40

COLOURS_BY_ID = {c.colour_id: c for c in COLOURS + GLAZING}

# What the hidden support columns are built from. One cheap, ubiquitous colour
# beats matching the surface: nobody sees it, and it keeps the shopping list short.
FILL_COLOUR_ID = 71  # Light Bluish Gray


def nearest_colour(rgb: tuple[int, int, int]) -> Colour:
    """Snap an arbitrary RGB value to the closest colour LEGO actually sells.

    Uses the "redmean" weighted distance, which tracks human colour perception
    far better than plain Euclidean RGB while needing no colour-space conversion.
    """
    r, g, b = rgb
    best = COLOURS[0]
    best_dist = float("inf")
    for colour in COLOURS:
        cr, cg, cb = colour.rgb
        rmean = (r + cr) / 2
        dr, dg, db = r - cr, g - cg, b - cb
        dist = (
            (2 + rmean / 256) * dr * dr
            + 4 * dg * dg
            + (2 + (255 - rmean) / 256) * db * db
        )
        if dist < best_dist:
            best_dist = dist
            best = colour
    return best


def choose_baseplate(grid_w: int, grid_h: int) -> dict[str, object]:
    """Pick the baseplate arrangement that covers the build area."""
    for part_num, name, bw, bh in BASEPLATES:
        if grid_w <= bw and grid_h <= bh:
            return {"partId": part_num, "name": name, "quantity": 1}
    # Larger than a single 32x32 — tile them.
    part_num, name, bw, bh = BASEPLATES[0]
    across = -(-grid_w // bw)
    down = -(-grid_h // bh)
    return {"partId": part_num, "name": name, "quantity": across * down}
